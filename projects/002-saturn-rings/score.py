"""Original deterministic orbital-wonder score; no sampled music."""
import json, hashlib
from pathlib import Path
import numpy as np
import soundfile as sf
p=Path(__file__).parent
length=json.loads((p/'output/docs/audio-timeline.json').read_text())['durationSeconds']+2
sr=48000;t=np.arange(int(length*sr))/sr;out=np.zeros((len(t),2))
chords=[[52,59,64,66],[48,55,60,64],[43,55,59,62],[50,57,62,66]]
def note(start,dur,midi,amp,pan=0):
 idx=int(start*sr);n=min(int(dur*sr),len(t)-idx)
 if n<=0:return
 u=np.arange(n)/sr;f=440*2**((midi-69)/12)
 env=(1-np.exp(-u*25))*np.exp(-u*1.7)*np.minimum(1,(dur-u)/.15)
 wave=(np.sin(2*np.pi*f*u)+.22*np.sin(2*np.pi*f*2*u)+.07*np.sin(2*np.pi*f*3*u))*env*amp
 out[idx:idx+n,0]+=wave*(.8-.2*pan);out[idx:idx+n,1]+=wave*(.8+.2*pan)
for k,start in enumerate(np.arange(0,length,.48)):
 c=chords[int(start//7.68)%4];note(start,1.9,c[[0,2,1,3,2,1,3,2][k%8]]+12,.12 if start<22 else .15,np.sin(k)*.7)
 if k%4==0:note(start,2.1,c[0]-12,.18)
 if k%16==0:
  for n in c:note(start,4,n,.065)
out=np.tanh(out)
sf.write(p/'assets/music/orbital-wonder.wav',out,sr,subtype='PCM_16')
f=p/'assets/music/orbital-wonder.wav'
(p/'assets/sources.json').write_text(json.dumps({'schemaVersion':1,'assets':[{'file':'assets/music/orbital-wonder.wav','source':'Original procedural score generated by project score.py','license':'Original work created for this project; no third-party samples','checksum':'sha256:'+hashlib.sha256(f.read_bytes()).hexdigest()},{'file':'renderer/index.tsx','source':'Original procedural planet, rings and ice geometry','license':'Original work created for this project'}]},indent=2)+'\n')
